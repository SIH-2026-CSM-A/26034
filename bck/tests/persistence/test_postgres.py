"""The migration, and the schema as PostgreSQL actually builds it.

Two things live here that cannot be proved anywhere else: that the migration applies,
reverses and reapplies cleanly, and that everything the scan path writes survives a round
trip through real ``jsonb``, real native enum types and the async session the application
uses.
"""

